// score from the side to move's point of view, in centipawns
int evaluate(const Board *b) {
    int score = 0;
    for (int p = PAWN; p <= KING; p++) {
        // a1 is square 0 but the tables start at a8, so white flips the rank
        // with sq ^ 56. black reads the table as is, which mirrors it
        U64 white = b->pieces[WHITE][p];
        while (white) score += value[p] + pst[p][pop_lsb(&white) ^ 56];

        U64 black = b->pieces[BLACK][p];
        while (black) score -= value[p] + pst[p][pop_lsb(&black)];
    }
    return b->side == WHITE ? score : -score;
}
